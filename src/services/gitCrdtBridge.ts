/**
 * Compute common prefix and suffix to apply minimal character delta to Y.Text
 * Preserves remote cursor positions and undo history for untouched ranges.
 */
export function applyTextDelta(
  ytext: Y.Text,
  oldText: string,
  newText: string,
  origin = 'git-reconcile'
): void {
  if (oldText === newText) return;

  let start = 0;
  while (start < oldText.length && start < newText.length && oldText[start] === newText[start]) {
    start++;
  }

  let oldEnd = oldText.length;
  let newEnd = newText.length;
  while (oldEnd > start && newEnd > start && oldText[oldEnd - 1] === newText[newEnd - 1]) {
    oldEnd--;
    newEnd--;
  }

  const deleteCount = oldEnd - start;
  const insertText = newText.slice(start, newEnd);

  const doc = ytext.doc;
  if (doc) {
    doc.transact(() => {
      if (deleteCount > 0) {
        ytext.delete(start, deleteCount);
      }
      if (insertText.length > 0) {
        ytext.insert(start, insertText);
      }
    }, origin);
  } else {
    if (deleteCount > 0) {
      ytext.delete(start, deleteCount);
    }
    if (insertText.length > 0) {
      ytext.insert(start, insertText);
    }
  }
}

/**
 * Parse conflict hunks from text generated by 3-way merge
 */
export function parseConflictHunks(mergedText: string): ConflictHunk[] {
  const lines = mergedText.split(/\r?\n/);
  const hunks: ConflictHunk[] = [];
  let inConflict = false;
  let inRemote = false;
  let currentLive: string[] = [];
  let currentRemote: string[] = [];
  let hunkIndex = 0;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? '';
    if (line.startsWith('<<<<<<<')) {
      inConflict = true;
      inRemote = false;
      currentLive = [];
      currentRemote = [];
    } else if (inConflict && line.startsWith('=======')) {
      inRemote = true;
    } else if (inConflict && line.startsWith('>>>>>>>')) {
      inConflict = false;
      inRemote = false;
      hunks.push({
        id: `hunk-${hunkIndex}`,
        index: hunkIndex,
        liveContent: currentLive.join('\n'),
        remoteContent: currentRemote.join('\n'),
        chosen: null,
      });
      hunkIndex++;
    } else if (inConflict) {
      if (inRemote) {
        currentRemote.push(line);
      } else {
        currentLive.push(line);
      }
    }
  }

  return hunks;
}

/**
 * Reassemble document from 3-way merged text and per-hunk resolution choices
 */
export function assembleResolvedDocument(
  mergedWithMarkers: string,
  hunkChoices: Record<number, 'live' | 'remote' | string>
): string {
  const lines = mergedWithMarkers.split(/\r?\n/);
  const resultLines: string[] = [];
  let inConflict = false;
  let inRemote = false;
  let currentLive: string[] = [];
  let currentRemote: string[] = [];
  let hunkIndex = 0;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? '';
    if (line.startsWith('<<<<<<<')) {
      inConflict = true;
      inRemote = false;
      currentLive = [];
      currentRemote = [];
    } else if (inConflict && line.startsWith('=======')) {
      inRemote = true;
    } else if (inConflict && line.startsWith('>>>>>>>')) {
      inConflict = false;
      inRemote = false;
      const choice = hunkChoices[hunkIndex];
      if (choice === 'live') {
        resultLines.push(...currentLive);
      } else if (choice === 'remote') {
        resultLines.push(...currentRemote);
      } else if (typeof choice === 'string') {
        resultLines.push(choice);
      } else {
        // default to live
        resultLines.push(...currentLive);
      }
      hunkIndex++;
    } else if (inConflict) {
      if (inRemote) {
        currentRemote.push(line);
      } else {
        currentLive.push(line);
      }
    } else {
      resultLines.push(line);
    }
  }

  return resultLines.join('\n');
}

export interface ReconcileOutcome {
  status: 'clean' | 'conflict' | 'up-to-date';
  filePath: string;
  mergedText: string;
  conflictCount?: number;
  hunks?: ConflictHunk[];
}

export class GitCrdtBridge {
  private static instance: GitCrdtBridge | null = null;

  // Stores S_base (content at HEAD commit when session initialized or last synced) per filePath
  private baseStates: Map<string, string> = new Map();

  private constructor() {}

  public static getInstance(): GitCrdtBridge {
    if (!GitCrdtBridge.instance) {
      GitCrdtBridge.instance = new GitCrdtBridge();
    }
    return GitCrdtBridge.instance;
  }

  /**
   * Record S_base for a file
   */
  public setBase(filePath: string, content: string): void {
    this.baseStates.set(filePath, content);
  }

  /**
   * Retrieve S_base for a file
   */
  public getBase(filePath: string): string | undefined {
    return this.baseStates.get(filePath);
  }

  /**
   * 3-Way CRDT-to-Git Reconciliation Algorithm (Subsystem B.3):
   * Reconciles (S_base, S_crdt, S_remote)
   */
  public async reconcileFile(
    filePath: string,
    remoteContent: string,
    projectDir?: string
  ): Promise<ReconcileOutcome> {
    const ytext = collabManager.getYText(filePath);
    const crdtContent = ytext.toString();

    // Retrieve or default S_base
    let base = this.baseStates.get(filePath);
    if (base === undefined) {
      base = crdtContent;
      this.baseStates.set(filePath, base);
    }

    // Fast path 1: Remote equals base -> CRDT wins, nothing incoming
    if (remoteContent === base) {
      return {
        status: 'up-to-date',
        filePath,
        mergedText: crdtContent,
      };
    }

    // Fast path 2: CRDT equals remote -> trivially clean
    if (crdtContent === remoteContent) {
      this.baseStates.set(filePath, remoteContent);
      return {
        status: 'clean',
        filePath,
        mergedText: remoteContent,
      };
    }

    // Fast path 3: CRDT didn't change from base, but remote changed -> remote wins cleanly
    if (crdtContent === base) {
      applyTextDelta(ytext, crdtContent, remoteContent, 'git-reconcile');
      this.baseStates.set(filePath, remoteContent);
      useWorkspaceStore.getState().updateFileContent(filePath, remoteContent);

      if (projectDir) {
        try {
          await writeFileText(filePath, remoteContent);
          useWorkspaceStore.getState().markFileSaved(filePath);
        } catch (e) {
          logger.warn('GitCRDT', 'Failed to write remote file to disk', {
            error: formatErrorDetails(e),
            filePath,
          });
        }
      }

      return {
        status: 'clean',
        filePath,
        mergedText: remoteContent,
      };
    }

    // Both CRDT and Remote diverged from S_base -> 3-way merge
    const result = await gitReconcile3Way(base, crdtContent, remoteContent);

    if (result.clean && !result.hasConflicts) {
      // Clean merge: apply minimal delta to Y.Text
      applyTextDelta(ytext, crdtContent, result.mergedText, 'git-reconcile');
      this.baseStates.set(filePath, result.mergedText);
      useWorkspaceStore.getState().updateFileContent(filePath, result.mergedText);

      if (projectDir) {
        try {
          await writeFileText(filePath, result.mergedText);
          useWorkspaceStore.getState().markFileSaved(filePath);
        } catch (e) {
          logger.warn('GitCRDT', 'Failed to write cleanly merged file to disk', {
            error: formatErrorDetails(e),
            filePath,
          });
        }
      }

      return {
        status: 'clean',
        filePath,
        mergedText: result.mergedText,
      };
    }

    // Conflicts detected -> parse hunks and surface ConflictModal
    const hunks = parseConflictHunks(result.mergedText);
    const conflictState: ConflictState = {
      filePath,
      baseText: base,
      crdtText: crdtContent,
      remoteText: remoteContent,
      mergedWithMarkers: result.mergedText,
      hunks,
    };

    useCollabStore.getState().setActiveConflict(conflictState);

    return {
      status: 'conflict',
      filePath,
      mergedText: result.mergedText,
      conflictCount: result.conflictCount || hunks.length,
      hunks,
    };
  }

  /**
   * Apply user resolution from ConflictModal
   */
  public async resolveConflict(
    filePath: string,
    resolvedText: string,
    projectDir?: string
  ): Promise<void> {
    const ytext = collabManager.getYText(filePath);
    const crdtContent = ytext.toString();

    applyTextDelta(ytext, crdtContent, resolvedText, 'git-reconcile');
    this.baseStates.set(filePath, resolvedText);
    useWorkspaceStore.getState().updateFileContent(filePath, resolvedText);

    if (projectDir) {
      try {
        await writeFileText(filePath, resolvedText);
        useWorkspaceStore.getState().markFileSaved(filePath);
      } catch (e) {
        logger.warn('GitCRDT', 'Failed to save resolved file to disk', {
          error: formatErrorDetails(e),
          filePath,
        });
      }
    }

    useCollabStore.getState().setActiveConflict(null);
  }

  /**
   * Designated Committer Push Guard (Subsystem B.2)
   */
  public async designatedCommitterPush(
    projectDir: string,
    message: string,
    remoteName?: string,
    branch?: string
  ): Promise<string> {
    const collabStatus = useCollabStore.getState().status;
    const isCommitter = useCollabStore.getState().isCommitter;
    const designatedCommitterId = useCollabStore.getState().designatedCommitterId;
    const peers = useCollabStore.getState().peers;

    if (collabStatus === 'connected' && peers.length > 1 && !isCommitter) {
      const leaderPeer = peers.find((p) => p.clientId === designatedCommitterId);
      const leaderName = leaderPeer ? leaderPeer.username : `Client #${designatedCommitterId}`;
      throw new Error(
        `Push rejected: Only the elected Designated Committer (@${leaderName}) can push to GitHub during a live collaborative session.`
      );
    }

    // Stage all files
    await gitStageAll(projectDir);

    // Commit
    const commitHash = await gitCommit(projectDir, message);

    // Push
    await gitPush(projectDir, remoteName, branch);

    return commitHash;
  }
}

export const gitCrdtBridge = GitCrdtBridge.getInstance();
